"""Build a PDF of the math-augmented framework (math-augmented-praxeo/).

Usage: python3 tools/build_math_pdf.py [out.pdf]

Concatenates the annex README (as the introduction), MATH_CORE_RULES.md, SURVEY.md and the worked
annex examples into one document, and prints it to PDF the same way as the handbook
(tools/build_handbook_pdf.py: pandoc to HTML, headless Chromium to PDF).
"""
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_handbook_pdf import CHROMIUM, CSS, ROOT, demote, read  # noqa: E402

M = os.path.join(ROOT, "math-augmented-praxeo")


def chapter(path, title):
    """A file as one chapter: its own title replaced, later top-level headings demoted."""
    text = read(path)
    first, _, rest = text.partition("\n")
    rest = re.sub(r"(?m)^# ", "## ", rest)
    return f"# {title}\n{rest}"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(M, "Math_Augmented_Framework.pdf")
    parts = [
        chapter(os.path.join(M, "README.md"), "Introduction"),
        chapter(os.path.join(M, "MATH_CORE_RULES.md"), "Math core rules"),
        chapter(os.path.join(M, "SURVEY.md"), "Survey of mathematical methods"),
    ]
    ex = ["# Appendix. Worked annex examples\n\nGenerated by the scripts in `math-augmented-praxeo/examples/`. "
          "All ranges are illustrative unless marked as from the case."]
    for rel in ("examples/we001_annex.md", "examples/we013_annex.md",
                "examples/sf_1994/annex.md", "examples/sf_1994/premise_step.md"):
        ex.append(demote(read(os.path.join(M, rel))))
    parts.append("\n\n".join(ex))
    md = "\n\n".join(p.strip() for p in parts) + "\n"

    title = ('<div class="title-page"><h1 class="main">Math-Augmented Praxeology</h1>'
             "<p>A minimal mathematical annex to the praxeological analyser</p>"
             "<p>Math core rules, survey of methods, worked examples</p>"
             "<p style='font-size:10pt;color:#555'>Not praxeology: it sizes what the core rules have signed</p></div>")
    with tempfile.TemporaryDirectory() as tmp:
        src, css, before, html = (os.path.join(tmp, n) for n in ("m.md", "s.css", "t.html", "m.html"))
        open(src, "w", encoding="utf-8").write(md)
        open(css, "w").write(CSS)
        open(before, "w").write(title)
        subprocess.run(["pandoc", src, "-f", "gfm", "-t", "html5", "-s", "--toc", "--toc-depth=2",
                        "--metadata", "title=Math-Augmented Praxeology", "--metadata", "pagetitle=Math-Augmented Praxeology",
                        "-V", "title=", "--css", css, "--embed-resources", "--include-before-body", before, "-o", html],
                       check=True)
        page = re.sub(r'<header id="title-block-header">.*?</header>', "", read(html), flags=re.S)
        open(html, "w", encoding="utf-8").write(page)
        chrome = next(p for p in CHROMIUM if os.path.exists(p))
        subprocess.run([chrome, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                        f"--print-to-pdf={out}", "file://" + html],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(out)


if __name__ == "__main__":
    main()
