"""Math annex for WE-013 (Halvern steel safeguard tariff, 25%; imports about 40% of use).

Run: python3 math-augmented-praxeo/examples/we013_annex.py  (writes we013_annex.md next to it)

Every elasticity, share and pass-through range below is ILLUSTRATIVE, not an estimate.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from mathpraxeo.interval import Interval  # noqa: E402
from mathpraxeo.report import annex_table  # noqa: E402
from mathpraxeo.result import Result  # noqa: E402
from mathpraxeo.statics import cost_pass_through, tariff  # noqa: E402

T = 0.25                          # WE-013 K1
IMPORT_SHARE = Interval(0.38, 0.42)  # WE-013 record: domestic firms supply about 60%
ED = Interval(-0.6, -0.2)         # steel demand elasticity, medium run (illustrative)
ES = Interval(0.2, 1.0)           # domestic steel supply elasticity, medium run (illustrative)
PASS = (0.6, 1.0)                 # share of the tariff in the domestic price (illustrative; 1 for a small buyer)
STEEL_SHARE_CONSTRUCTION = Interval(0.03, 0.10)  # steel in construction costs (illustrative)


def main() -> str:
    r = tariff(T, IMPORT_SHARE, ED, ES, PASS)
    rev = Result("revenue_vs_static_projection", r["imports"].value, "M1", r["imports"].assumptions,
                 "Revenue falls short of the static projection (tariff x old imports) by the fall in imports.")
    constr = cost_pass_through(r["domestic_price"].value, STEEL_SHARE_CONSTRUCTION)
    rows = [
        ("C-6 steel users, price_paid (domestic steel)", "increase", r["domestic_price"], "tariff passed into the domestic price"),
        ("C-2 domestic steelmakers, quantity_supplied", "increase", r["domestic_output"], "supply response to the higher price"),
        ("C-7 importers, quantity_traded (imports)", "decrease", r["imports"], "use minus domestic output"),
        ("C-27 steel users, quantity_traded (steel bought)", "decrease", r["use"], "demand response"),
        ("C-25 tariff revenue vs static projection", "decrease", rev, "share of the static projection lost"),
        ("C-24 construction buyers, price_paid", "increase", constr, "steel's share of construction costs"),
    ]
    return annex_table(
        "WE-013 math annex (illustrative ranges)",
        "Generated by `examples/we013_annex.py`. Every elasticity, share and pass-through range is illustrative, not an "
        "estimate. The annex sizes six consequences that WE-013 signed and checks each range against the sign. "
        "It changes no sign.",
        rows)


if __name__ == "__main__":
    text = main()
    Path(__file__).with_suffix(".md").write_text(text)
    print(text)
