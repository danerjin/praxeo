"""Math annex for WE-001 (Riverton rent freeze): sizes for three consequences the
praxeological analysis signed, and a check that every range agrees with its sign.

Run: python3 math-augmented-praxeo/examples/we001_annex.py  (writes we001_annex.md next to it)

Every elasticity, rate and duration below is an ILLUSTRATIVE range, not an estimate:
a real annex must cite a source for each.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from mathpraxeo.capital import cap_gap_path, capitalized_loss, gap_share  # noqa: E402
from mathpraxeo.interval import Interval  # noqa: E402
from mathpraxeo.report import annex_table  # noqa: E402
from mathpraxeo.statics import ceiling_quantity_supplied, ceiling_shortage  # noqa: E402

MARKET = Interval(0.03, 0.07)          # WE-001 record: about 5% a year; range illustrative
CAP = [0, 0, 0] + [0.02] * 17          # frozen 3 years, then 2% a year (WE-001 K1)
ED = Interval(-0.5, -0.1)              # rental demand elasticity (illustrative)
ES_SHORT = Interval(0.0, 0.2)          # supply elasticity, short run (illustrative)
ES_LONG = Interval(0.3, 1.0)           # supply elasticity, long run (illustrative)
RATE = Interval(0.04, 0.08)            # buyers' discount rate (illustrative)
DURATION = Interval(5, 15)             # years buyers expect the ordinance to last (WE-001 A-13; illustrative)


def main() -> str:
    gaps = cap_gap_path(20, MARKET, CAP)
    rows = []

    g3 = gap_share(gaps[2], MARKET, 3)
    short = ceiling_shortage(g3, ED, ES_SHORT)
    rows.append(("C-2 excess_demand (year 3)", "increase", short,
                 f"gap in year 3 = {g3} of the market rent"))

    g10 = gap_share(gaps[9], MARKET, 10)
    supply = ceiling_quantity_supplied(g10, ES_LONG)
    rows.append(("C-9 quantity_supplied (year 10)", "decrease", supply,
                 f"gap in year 10 = {g10} of the market rent"))

    loss = capitalized_loss(gaps, RATE, DURATION)
    value = loss.value * -1
    rows.append(("C-20 asset_value (at announcement)", "decrease",
                 type(loss)(loss.name, value, loss.rung, loss.assumptions, loss.note),
                 "change in building value, in years of today's rent"))

    text = annex_table(
        "WE-001 math annex (illustrative ranges)",
        "Generated by `examples/we001_annex.py`. Every elasticity, rate and duration is an illustrative range, "
        "not an estimate. The annex sizes three consequences that WE-001 signed and checks that each range agrees "
        "with the sign. It changes no sign.",
        rows)
    out = [text]
    out += ["", "Gap path (market minus capped rent, in units of today's rent): " +
            ", ".join(f"y{k + 1} {gaps[k].value}" for k in (0, 2, 4, 9, 14)), ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = main()
    (Path(__file__).with_suffix(".md")).write_text(text)
    print(text)
